import { chromium } from "@playwright/test";
const base = "http://localhost:3000";
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto(`${base}/login`);
await page.fill("#email", "dj@geartractor.app");
await page.fill("#password", "GearTractor!2026");
await Promise.all([page.waitForURL("**/dashboard"), page.click("button[type=submit]")]);
await page.getByText("In Progress Checkout").click();
await page.waitForURL("**/edit**");
await page.goto(page.url().split("?")[0] + "?step=2");
await page.getByRole("radio", { name: /DJ Fernandez/ }).click();
await page.getByRole("button", { name: /Continue/ }).click();
await page.getByRole("radio", { name: /Workshop/ }).click();
await page.getByRole("button", { name: /Continue/ }).click();
await page.getByPlaceholder("Search by ID, name or tech spec").fill("Chainsaw 3");
await page.getByRole("button", { name: "Add", exact: true }).first().click();
await page.waitForTimeout(1200);
await page.getByPlaceholder("Search by ID, name or tech spec").fill("Fuel");
await page.getByLabel(/Quantity of Fuel/).first().fill("2");
await page.getByRole("button", { name: "Add", exact: true }).first().click();
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/flow_basket.png`, fullPage: true });
await page.getByRole("button", { name: /Review Checkout/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/flow_review.png`, fullPage: true });
await page.getByRole("button", { name: /Confirm Checkout/ }).click();
await page.getByText("Checkout completed").first().waitFor({ timeout: 15000 });
await page.screenshot({ path: `${out}/flow_done.png` });
await page.getByRole("link", { name: /View session/ }).click();
await page.waitForURL(/checkouts\/[0-9a-f-]+$/);
await page.getByRole("link", { name: /Check In/ }).first().click();
await page.waitForURL("**/return");
await page.screenshot({ path: `${out}/flow_return.png`, fullPage: true });
await page.getByRole("radio", { name: "Damaged" }).first().click();
await page.getByPlaceholder("Add a note").first().fill("Chain guard cracked");
// fuel: 1 unused, 1 consumed
const unused = page.locator("input[inputmode=decimal]");
await unused.nth(0).fill("1");
await unused.nth(1).fill("1");
await page.getByRole("button", { name: /Check in/ }).last().click();
await page.getByText("Equipment returned").first().waitFor({ timeout: 15000 });
await page.screenshot({ path: `${out}/flow_returned.png` });
console.log("FLOW OK", errors.length ? errors : "");
await browser.close();
